import assert from 'node:assert/strict';
import fs from 'node:fs';
import ts from 'typescript';
import { createRequire } from 'node:module';
const load = createRequire(import.meta.url);
load.extensions['.ts'] = (module, file) => module._compile(ts.transpileModule(fs.readFileSync(file, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText, file);
const { createJudgeWorkspace, judgeActor } = load('../src/lib/judge-demo.ts');
const { applyReview, readiness, expiredEvidence } = load('../src/lib/governance.ts');
const { publicationChecks } = load('../src/lib/publishing.ts');
const { buildPassport } = load('../src/lib/passport.ts');
const workspace = await createJudgeWorkspace();
assert.equal(workspace.records.length, 4);
let record = workspace.records[0];
assert(record.findings.length > 0);
while (record.findings.length) record = await applyReview(record, { action: 'accept', findingId: record.findings[0].id, actor: judgeActor, expectedRevision: record.governance.revision }, workspace.pack);
assert.equal(readiness(record).approved, false);
record = await applyReview(record, { action: 'approve', actor: judgeActor, expectedRevision: record.governance.revision }, workspace.pack);
assert((await publicationChecks(record, workspace.pack.version, record.governance.channel)).every(check => check.pass));
assert.equal(buildPassport(record, workspace.pack).status, 'approved_for_this_version');
record = await applyReview(record, { action: 'revise', text: record.body_text + ' A new version.', actor: judgeActor, expectedRevision: record.governance.revision }, workspace.pack);
assert.equal(readiness(record).approved, false);
const published = workspace.records[2];
assert.equal(published.governance.publication.status, 'drift');
assert.equal((await publicationChecks(published, workspace.pack.version, published.governance.channel)).find(check => check.id === 'publication').pass, false);
assert(expiredEvidence(workspace.expiredPack).length > 0);
await assert.rejects(applyReview(workspace.records[3], { action: 'approve', actor: judgeActor, expectedRevision: 1 }, workspace.expiredPack), /expired/);
const reset = await createJudgeWorkspace();
assert(reset.records[0].findings.length > 0);
assert.equal(reset.records[0].governance.version, 1);
console.log('PASS: four judge scenarios, focused fixes, approval, gate, passport, edit invalidation, published drift, expired evidence, fresh reset.');
